//! Phase 1 Z80 code generator lowering `aun-ir` + *Uchiguri* static RAM layout to Z80 assembly.

use crate::uchiguri::RamLayout;
use aun_ir::*;
use std::collections::{BTreeSet, HashMap};
use std::fmt::Write;

/// Converts an IR function/method name (which may contain `::`) into a valid Z80 label.
pub fn z80_sym(name: &str) -> String {
    name.replace("::", "__")
}

/// Emits Z80 assembly text for all non-test functions in `program`.
pub fn emit_z80_asm(
    program: &IrProgram,
    layout: &RamLayout,
    code_origin: u16,
) -> Result<String, String> {
    let mut asm = String::new();
    writeln!(asm, "; Generated by aun-z80 (Phase 2)").unwrap();
    writeln!(asm, ".org 0x{code_origin:04X}").unwrap();
    writeln!(
        asm,
        "; Uchiguri RAM: 0x{:04X}..0x{:04X} ({} bytes), max stack: {} bytes",
        layout.ram_base,
        layout.ram_end,
        layout.ram_end.saturating_sub(layout.ram_base),
        layout.max_stack_bytes
    )
    .unwrap();

    let mut needs_panic_stub = false;
    let mut needs_noop_ret = false;

    for func in &program.functions {
        if func.is_test {
            continue;
        }
        let scratch_base = layout
            .fn_scratch_bases
            .get(&func.id)
            .copied()
            .unwrap_or(layout.ram_end);
        emit_function(
            program,
            func,
            layout,
            scratch_base,
            &mut needs_panic_stub,
            &mut asm,
        )?;
    }

    // Emit state machine dispatch tables, SMC stubs, and transition bitmasks
    for mdef in &program.machines {
        let mut method_names: BTreeSet<String> = BTreeSet::new();
        let mut has_on_exit = false;
        for st in &mdef.states {
            if st.on_exit.is_some() {
                has_on_exit = true;
            }
            for m in st.methods.keys() {
                method_names.insert(m.clone());
            }
        }
        // Transition bitmask table (2 bytes per source state, supports up to 16 states)
        writeln!(asm, "\n{}_tmask:", mdef.name).unwrap();
        for &mask in &mdef.transitions {
            writeln!(asm, "    .dw 0x{:04X}", (mask & 0xFFFF) as u16).unwrap();
        }
        if has_on_exit {
            needs_noop_ret = true;
            emit_dispatch_stub(
                program,
                mdef,
                "on_exit",
                false,
                |st| st.on_exit,
                &mut asm,
            );
        }
        for method in &method_names {
            needs_noop_ret = true;
            emit_dispatch_stub(
                program,
                mdef,
                method,
                mdef.smc,
                |st| st.methods.get(method).copied(),
                &mut asm,
            );
        }
    }

    if needs_noop_ret {
        writeln!(asm, "\n__aun_noop_ret:").unwrap();
        writeln!(asm, "    ret").unwrap();
    }

    let user_defined_panic = program.functions.iter().any(|f| !f.is_test && f.name == "__aun_panic")
        || program.externs.iter().any(|e| e.name == "__aun_panic");
    if needs_panic_stub && !user_defined_panic {
        writeln!(asm, "\n__aun_panic:").unwrap();
        writeln!(asm, "    di").unwrap();
        writeln!(asm, "    halt").unwrap();
    }

    Ok(asm)
}

fn emit_dispatch_stub<F>(
    program: &IrProgram,
    mdef: &MachineDef,
    method: &str,
    use_smc: bool,
    resolve_fn: F,
    asm: &mut String,
) where
    F: Fn(&StateDef) -> Option<u32>,
{
    let vtbl_lbl = format!("{}_vtbl_{method}", mdef.name);
    let disp_lbl = format!("{}_disp_{method}", mdef.name);

    writeln!(asm, "\n{vtbl_lbl}:").unwrap();
    for st in &mdef.states {
        let target = resolve_fn(st)
            .map(|fid| z80_sym(&program.functions[fid as usize].name))
            .unwrap_or_else(|| "__aun_noop_ret".to_string());
        writeln!(asm, "    .dw {target}").unwrap();
    }

    writeln!(asm, "{disp_lbl}:").unwrap();
    if use_smc {
        // Self-modifying direct JP (10T, 3B) — patched in RAM on every transition
        let init_target = resolve_fn(&mdef.states[mdef.initial_state as usize])
            .map(|fid| z80_sym(&program.functions[fid as usize].name))
            .unwrap_or_else(|| "__aun_noop_ret".to_string());
        writeln!(asm, "    jp {init_target}").unwrap();
    } else {
        // Table-driven dispatch preserving HL = self
        writeln!(asm, "    push hl").unwrap();
        if mdef.tag_offset > 0 {
            writeln!(asm, "    ld de, 0x{:04X}", mdef.tag_offset).unwrap();
            writeln!(asm, "    add hl, de").unwrap();
        }
        writeln!(asm, "    ld a, (hl)").unwrap();
        writeln!(asm, "    add a, a").unwrap();
        writeln!(asm, "    ld e, a").unwrap();
        writeln!(asm, "    ld d, 0").unwrap();
        writeln!(asm, "    ld hl, {vtbl_lbl}").unwrap();
        writeln!(asm, "    add hl, de").unwrap();
        writeln!(asm, "    ld e, (hl)").unwrap();
        writeln!(asm, "    inc hl").unwrap();
        writeln!(asm, "    ld d, (hl)").unwrap();
        writeln!(asm, "    pop hl").unwrap();
        writeln!(asm, "    push de").unwrap();
        writeln!(asm, "    ret").unwrap();
    }
}

fn val_addr(scratch_base: u16, v: ValueId) -> u16 {
    scratch_base.wrapping_add((v as u16) * 2)
}

fn is_signed_ty(ty: &IrType) -> bool {
    match ty {
        IrType::Int(it) | IrType::Fixed { base: it, .. } => it.is_signed(),
        _ => false,
    }
}

fn collect_val_sizes(program: &IrProgram, func: &IrFunction) -> HashMap<ValueId, u16> {
    let mut sizes = HashMap::new();
    for bb in &func.blocks {
        for inst in &bb.insts {
            match inst {
                IrInst::ConstInt { dst, ty, .. } => {
                    sizes.insert(*dst, program.type_size(ty));
                }
                IrInst::ConstBool { dst, .. } | IrInst::StateTag { dst, .. } => {
                    sizes.insert(*dst, 1);
                }
                IrInst::BinOp { dst, op, ty, .. } => {
                    let sz = match op {
                        IrBinOp::Eq
                        | IrBinOp::Ne
                        | IrBinOp::Lt
                        | IrBinOp::Le
                        | IrBinOp::Gt
                        | IrBinOp::Ge => 1,
                        _ => program.type_size(ty),
                    };
                    sizes.insert(*dst, sz);
                }
                IrInst::UnOp { dst, ty, .. } => {
                    sizes.insert(*dst, program.type_size(ty));
                }
                IrInst::Cast { dst, to_ty, .. } => {
                    sizes.insert(*dst, program.type_size(to_ty));
                }
                IrInst::FixedInt { dst, base, .. } => {
                    sizes.insert(*dst, base.byte_size());
                }
                IrInst::LoadLocal { dst, ty, .. } | IrInst::LoadPtr { dst, ty, .. } => {
                    sizes.insert(*dst, program.type_size(ty));
                }
                IrInst::AddrLocal { dst, .. }
                | IrInst::AddrGlobal { dst, .. }
                | IrInst::FieldAddr { dst, .. }
                | IrInst::IndexAddr { dst, .. }
                | IrInst::PoolElemAddr { dst, .. } => {
                    sizes.insert(*dst, 2);
                }
                IrInst::PoolAlloc { dst, .. } | IrInst::PortIn { dst, .. } => {
                    sizes.insert(*dst, 1);
                }
                IrInst::Call {
                    dst: Some(d),
                    func: callee_id,
                    ..
                } => {
                    let sz = program
                        .functions
                        .get(*callee_id as usize)
                        .map(|f| program.type_size(&f.ret_ty))
                        .unwrap_or(2);
                    sizes.insert(*d, sz);
                }
                IrInst::ExternCall {
                    dst: Some(d),
                    extern_fn,
                    ..
                } => {
                    let sz = program
                        .externs
                        .get(*extern_fn as usize)
                        .and_then(|e| e.ret.as_ref())
                        .map(|(ty, _)| program.type_size(ty))
                        .unwrap_or(2);
                    sizes.insert(*d, sz);
                }
                _ => {}
            }
        }
    }
    sizes
}

fn emit_function(
    program: &IrProgram,
    func: &IrFunction,
    layout: &RamLayout,
    scratch_base: u16,
    needs_panic_stub: &mut bool,
    asm: &mut String,
) -> Result<(), String> {
    let fname = z80_sym(&func.name);
    writeln!(asm, "\n{fname}:").unwrap();

    // Entry: 1st param passed in A (1-byte) or HL (2-byte); remaining params are already
    // written directly into this function's Uchiguri parameter slots by the caller.
    if func.param_count > 0 {
        let p0 = &func.locals[0];
        let p0_addr = layout.slot_addrs[&(func.id, p0.id)];
        match program.type_size(&p0.ty) {
            1 => writeln!(asm, "    ld (0x{p0_addr:04X}), a").unwrap(),
            2 => writeln!(asm, "    ld (0x{p0_addr:04X}), hl").unwrap(),
            _ => {}
        }
    }

    let val_sizes = collect_val_sizes(program, func);
    let mut label_counter = 0u32;

    for (bb_idx, bb) in func.blocks.iter().enumerate() {
        writeln!(asm, "{fname}_bb{}:", bb.id).unwrap();
        for inst in &bb.insts {
            emit_inst(
                program,
                func,
                inst,
                layout,
                scratch_base,
                &val_sizes,
                &mut label_counter,
                needs_panic_stub,
                asm,
            )?;
        }
        let next_bb_id = func.blocks.get(bb_idx + 1).map(|b| b.id);
        match bb.term {
            Terminator::Return(Some(v)) => {
                let va = val_addr(scratch_base, v);
                match program.type_size(&func.ret_ty) {
                    1 => writeln!(asm, "    ld a, (0x{va:04X})").unwrap(),
                    2 => writeln!(asm, "    ld hl, (0x{va:04X})").unwrap(),
                    _ => {}
                }
                writeln!(asm, "    ret").unwrap();
            }
            Terminator::Return(None) => {
                writeln!(asm, "    ret").unwrap();
            }
            Terminator::Goto(target) => {
                if next_bb_id != Some(target) {
                    writeln!(asm, "    jp {fname}_bb{target}").unwrap();
                }
            }
            Terminator::Branch {
                cond,
                then_bb,
                else_bb,
            } => {
                let ca = val_addr(scratch_base, cond);
                writeln!(asm, "    ld a, (0x{ca:04X})").unwrap();
                writeln!(asm, "    or a").unwrap();
                if next_bb_id == Some(then_bb) {
                    writeln!(asm, "    jp z, {fname}_bb{else_bb}").unwrap();
                } else {
                    writeln!(asm, "    jp nz, {fname}_bb{then_bb}").unwrap();
                    if next_bb_id != Some(else_bb) {
                        writeln!(asm, "    jp {fname}_bb{else_bb}").unwrap();
                    }
                }
            }
            Terminator::Unreachable => {
                writeln!(asm, "    halt").unwrap();
            }
        }
    }
    Ok(())
}

fn fresh_label(func: &IrFunction, tag: &str, counter: &mut u32) -> String {
    let id = *counter;
    *counter += 1;
    format!("{}_{tag}_{id}", z80_sym(&func.name))
}

#[allow(clippy::too_many_arguments)]
fn emit_inst(
    program: &IrProgram,
    func: &IrFunction,
    inst: &IrInst,
    layout: &RamLayout,
    scratch_base: u16,
    val_sizes: &HashMap<ValueId, u16>,
    label_counter: &mut u32,
    needs_panic_stub: &mut bool,
    asm: &mut String,
) -> Result<(), String> {
    match inst {
        IrInst::ConstInt { dst, ty, val } => {
            let da = val_addr(scratch_base, *dst);
            match program.type_size(ty) {
                1 => {
                    let b = (*val & 0xFF) as u8;
                    if b == 0 {
                        writeln!(asm, "    xor a").unwrap();
                    } else {
                        writeln!(asm, "    ld a, 0x{b:02X}").unwrap();
                    }
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                2 => {
                    let w = *val as u16;
                    writeln!(asm, "    ld hl, 0x{w:04X}").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::ConstBool { dst, val } => {
            let da = val_addr(scratch_base, *dst);
            if *val {
                writeln!(asm, "    ld a, 1").unwrap();
            } else {
                writeln!(asm, "    xor a").unwrap();
            }
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        IrInst::LoadLocal { dst, slot, ty } => {
            let sa = layout.slot_addrs[&(func.id, *slot)];
            let da = val_addr(scratch_base, *dst);
            match program.type_size(ty) {
                1 => {
                    writeln!(asm, "    ld a, (0x{sa:04X})").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld hl, (0x{sa:04X})").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::StoreLocal { slot, val, ty } => {
            let sa = layout.slot_addrs[&(func.id, *slot)];
            let va = val_addr(scratch_base, *val);
            match program.type_size(ty) {
                1 => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (0x{sa:04X}), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (0x{sa:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::AddrLocal { dst, slot } => {
            let sa = layout.slot_addrs[&(func.id, *slot)];
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, 0x{sa:04X}").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::AddrGlobal { dst, global } => {
            let ga = layout.global_addrs[global];
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, 0x{ga:04X}").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::FieldAddr {
            dst,
            base,
            byte_offset,
        } => {
            let ba = val_addr(scratch_base, *base);
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, (0x{ba:04X})").unwrap();
            if *byte_offset > 0 {
                writeln!(asm, "    ld de, 0x{byte_offset:04X}").unwrap();
                writeln!(asm, "    add hl, de").unwrap();
            }
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::IndexAddr {
            dst,
            base,
            index,
            elem_size,
            len,
            site_id,
        } => {
            let ba = val_addr(scratch_base, *base);
            let ia = val_addr(scratch_base, *index);
            let da = val_addr(scratch_base, *dst);
            let idx_size = val_sizes.get(index).copied().unwrap_or(1);
            if idx_size == 1 {
                writeln!(asm, "    ld a, (0x{ia:04X})").unwrap();
                writeln!(asm, "    ld l, a").unwrap();
                writeln!(asm, "    ld h, 0").unwrap();
            } else {
                writeln!(asm, "    ld hl, (0x{ia:04X})").unwrap();
            }

            // Bounds check: index < len
            if *len > 0 {
                *needs_panic_stub = true;
                let ok_lbl = fresh_label(func, "idx_ok", label_counter);
                writeln!(asm, "    push hl").unwrap();
                writeln!(asm, "    ld de, 0x{len:04X}").unwrap();
                writeln!(asm, "    or a").unwrap();
                writeln!(asm, "    sbc hl, de").unwrap();
                writeln!(asm, "    pop hl").unwrap();
                writeln!(asm, "    jr c, {ok_lbl}").unwrap();
                writeln!(asm, "    ld a, {}", PanicCode::Bounds as u8).unwrap();
                writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
                writeln!(asm, "    call __aun_panic").unwrap();
                writeln!(asm, "{ok_lbl}:").unwrap();
            }

            // Multiply HL by constant elem_size
            emit_mul_hl_const(*elem_size, asm);

            // Add base address
            writeln!(asm, "    ld de, (0x{ba:04X})").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::LoadPtr { dst, addr, ty } => {
            let aa = val_addr(scratch_base, *addr);
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
            match program.type_size(ty) {
                1 => {
                    writeln!(asm, "    ld a, (hl)").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld e, (hl)").unwrap();
                    writeln!(asm, "    inc hl").unwrap();
                    writeln!(asm, "    ld d, (hl)").unwrap();
                    writeln!(asm, "    ex de, hl").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::StorePtr { addr, val, ty } => {
            let aa = val_addr(scratch_base, *addr);
            let va = val_addr(scratch_base, *val);
            match program.type_size(ty) {
                1 => {
                    writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (hl), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld de, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
                    writeln!(asm, "    ld (hl), e").unwrap();
                    writeln!(asm, "    inc hl").unwrap();
                    writeln!(asm, "    ld (hl), d").unwrap();
                }
                _ => {}
            }
        }
        IrInst::UnOp {
            dst, op, ty, val, ..
        } => {
            let va = val_addr(scratch_base, *val);
            let da = val_addr(scratch_base, *dst);
            match (op, ty, program.type_size(ty)) {
                (IrUnOp::Not, IrType::Bool, _) => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    xor 1").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                (IrUnOp::Not, _, 1) => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    cpl").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                (IrUnOp::Not, _, 2) => {
                    writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld a, l").unwrap();
                    writeln!(asm, "    cpl").unwrap();
                    writeln!(asm, "    ld l, a").unwrap();
                    writeln!(asm, "    ld a, h").unwrap();
                    writeln!(asm, "    cpl").unwrap();
                    writeln!(asm, "    ld h, a").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                (IrUnOp::Neg, _, 1) => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    neg").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                (IrUnOp::Neg, _, 2) => {
                    writeln!(asm, "    ld de, (0x{va:04X})").unwrap();
                    writeln!(asm, "    xor a").unwrap();
                    writeln!(asm, "    ld h, a").unwrap();
                    writeln!(asm, "    ld l, a").unwrap();
                    writeln!(asm, "    sbc hl, de").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::Cast {
            dst,
            val,
            from_ty,
            to_ty,
        } => {
            let va = val_addr(scratch_base, *val);
            let da = val_addr(scratch_base, *dst);
            let from_sz = program.type_size(from_ty);
            let to_sz = program.type_size(to_ty);
            match (from_sz, to_sz) {
                (1, 1) => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    if *to_ty == IrType::Bool && *from_ty != IrType::Bool {
                        let lbl = fresh_label(func, "cast_bool", label_counter);
                        writeln!(asm, "    or a").unwrap();
                        writeln!(asm, "    jr z, {lbl}").unwrap();
                        writeln!(asm, "    ld a, 1").unwrap();
                        writeln!(asm, "{lbl}:").unwrap();
                    }
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                (1, 2) => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld l, a").unwrap();
                    if is_signed_ty(from_ty) {
                        writeln!(asm, "    add a, a").unwrap();
                        writeln!(asm, "    sbc a, a").unwrap();
                        writeln!(asm, "    ld h, a").unwrap();
                    } else {
                        writeln!(asm, "    ld h, 0").unwrap();
                    }
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                (2, 1) => {
                    if *to_ty == IrType::Bool {
                        let lbl = fresh_label(func, "cast_bool", label_counter);
                        writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                        writeln!(asm, "    ld a, l").unwrap();
                        writeln!(asm, "    or h").unwrap();
                        writeln!(asm, "    jr z, {lbl}").unwrap();
                        writeln!(asm, "    ld a, 1").unwrap();
                        writeln!(asm, "{lbl}:").unwrap();
                        writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                    } else {
                        // Little-endian: low byte is at va
                        writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                        writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                    }
                }
                (2, 2) => {
                    writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::FixedInt {
            dst,
            val,
            base,
            frac_bits,
        } => {
            let va = val_addr(scratch_base, *val);
            let da = val_addr(scratch_base, *dst);
            match (base.byte_size(), *frac_bits) {
                (2, 8) => {
                    // q8_8::int() -> direct high-byte read (0T shift!), sign/zero extended to 16-bit
                    let va_hi = va.wrapping_add(1);
                    writeln!(asm, "    ld a, (0x{va_hi:04X})").unwrap();
                    writeln!(asm, "    ld l, a").unwrap();
                    if base.is_signed() {
                        writeln!(asm, "    add a, a").unwrap();
                        writeln!(asm, "    sbc a, a").unwrap();
                        writeln!(asm, "    ld h, a").unwrap();
                    } else {
                        writeln!(asm, "    ld h, 0").unwrap();
                    }
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                (2, 6) => {
                    // q10_6::int() -> exact 16-bit shift right by 6 via 2-bit left shift of A:H:L
                    writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                    if base.is_signed() {
                        writeln!(asm, "    ld a, h").unwrap();
                        writeln!(asm, "    add a, a").unwrap();
                        writeln!(asm, "    sbc a, a").unwrap();
                    } else {
                        writeln!(asm, "    xor a").unwrap();
                    }
                    writeln!(asm, "    sla l").unwrap();
                    writeln!(asm, "    rl h").unwrap();
                    writeln!(asm, "    rla").unwrap();
                    writeln!(asm, "    sla l").unwrap();
                    writeln!(asm, "    rl h").unwrap();
                    writeln!(asm, "    rla").unwrap();
                    writeln!(asm, "    ld l, h").unwrap();
                    writeln!(asm, "    ld h, a").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                (2, 0) => {
                    writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                (2, fb) => {
                    let lbl = fresh_label(func, "fxint", label_counter);
                    writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld b, {fb}").unwrap();
                    writeln!(asm, "{lbl}:").unwrap();
                    if base.is_signed() {
                        writeln!(asm, "    sra h").unwrap();
                    } else {
                        writeln!(asm, "    srl h").unwrap();
                    }
                    writeln!(asm, "    rr l").unwrap();
                    writeln!(asm, "    djnz {lbl}").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                (1, 0) => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                (1, fb) => {
                    let lbl = fresh_label(func, "fxint", label_counter);
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld b, {fb}").unwrap();
                    writeln!(asm, "{lbl}:").unwrap();
                    if base.is_signed() {
                        writeln!(asm, "    sra a").unwrap();
                    } else {
                        writeln!(asm, "    srl a").unwrap();
                    }
                    writeln!(asm, "    djnz {lbl}").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                _ => {}
            }
        }
        IrInst::BinOp {
            dst,
            op,
            mode,
            ty,
            lhs,
            rhs,
            ..
        } => {
            emit_binop(
                program,
                func,
                *dst,
                *op,
                *mode,
                ty,
                *lhs,
                *rhs,
                scratch_base,
                label_counter,
                asm,
            );
        }
        IrInst::PortOut { port, val } => {
            let pa = val_addr(scratch_base, *port);
            let va = val_addr(scratch_base, *val);
            writeln!(asm, "    ld a, (0x{pa:04X})").unwrap();
            writeln!(asm, "    ld c, a").unwrap();
            writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
            writeln!(asm, "    out (c), a").unwrap();
        }
        IrInst::PortIn { dst, port } => {
            let pa = val_addr(scratch_base, *port);
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld a, (0x{pa:04X})").unwrap();
            writeln!(asm, "    ld c, a").unwrap();
            writeln!(asm, "    in a, (c)").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        IrInst::Call {
            dst,
            func: callee_id,
            args,
        } => {
            let callee = &program.functions[*callee_id as usize];
            // Write arguments 1..N directly into callee's Uchiguri parameter slots
            for (idx, &arg_val) in args.iter().enumerate().skip(1) {
                if let Some(param_slot) = callee.locals.get(idx) {
                    let aa = val_addr(scratch_base, arg_val);
                    let pa = layout.slot_addrs[&(callee.id, param_slot.id)];
                    match program.type_size(&param_slot.ty) {
                        1 => {
                            writeln!(asm, "    ld a, (0x{aa:04X})").unwrap();
                            writeln!(asm, "    ld (0x{pa:04X}), a").unwrap();
                        }
                        2 => {
                            writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
                            writeln!(asm, "    ld (0x{pa:04X}), hl").unwrap();
                        }
                        _ => {}
                    }
                }
            }
            // Pass argument 0 in A (1-byte) or HL (2-byte)
            if let Some(&a0) = args.first()
                && let Some(p0) = callee.locals.first()
            {
                let aa = val_addr(scratch_base, a0);
                match program.type_size(&p0.ty) {
                    1 => writeln!(asm, "    ld a, (0x{aa:04X})").unwrap(),
                    2 => writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap(),
                    _ => {}
                }
            }
            writeln!(asm, "    call {}", z80_sym(&callee.name)).unwrap();
            if let Some(d) = dst {
                let da = val_addr(scratch_base, *d);
                match program.type_size(&callee.ret_ty) {
                    1 => writeln!(asm, "    ld (0x{da:04X}), a").unwrap(),
                    2 => writeln!(asm, "    ld (0x{da:04X}), hl").unwrap(),
                    _ => {}
                }
            }
        }
        IrInst::ExternCall {
            dst,
            extern_fn,
            args,
        } => {
            let ef = &program.externs[*extern_fn as usize];
            // Load non-A arguments first so `ld a, (addr); ld r, a` never clobbers an `in A` argument
            let mut deferred_a: Option<u16> = None;
            for (arg_val, (_, pty, reg)) in args.iter().zip(ef.params.iter()) {
                let aa = val_addr(scratch_base, *arg_val);
                let r = reg.to_ascii_lowercase();
                match program.type_size(pty) {
                    1 => {
                        if r == "a" {
                            deferred_a = Some(aa);
                        } else {
                            writeln!(asm, "    ld a, (0x{aa:04X})").unwrap();
                            writeln!(asm, "    ld {r}, a").unwrap();
                        }
                    }
                    2 => {
                        writeln!(asm, "    ld {r}, (0x{aa:04X})").unwrap();
                    }
                    _ => {}
                }
            }
            if let Some(aa) = deferred_a {
                writeln!(asm, "    ld a, (0x{aa:04X})").unwrap();
            }
            writeln!(asm, "    call {}", ef.name).unwrap();
            if let (Some(d), Some((rty, rreg))) = (dst, &ef.ret) {
                let da = val_addr(scratch_base, *d);
                let r = rreg.to_ascii_lowercase();
                match program.type_size(rty) {
                    1 => {
                        if r != "a" {
                            writeln!(asm, "    ld a, {r}").unwrap();
                        }
                        writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                    }
                    2 => writeln!(asm, "    ld (0x{da:04X}), {r}").unwrap(),
                    _ => {}
                }
            }
        }
        IrInst::Assert { cond, site_id } => {
            *needs_panic_stub = true;
            let ca = val_addr(scratch_base, *cond);
            let ok_lbl = fresh_label(func, "assert_ok", label_counter);
            writeln!(asm, "    ld a, (0x{ca:04X})").unwrap();
            writeln!(asm, "    or a").unwrap();
            writeln!(asm, "    jr nz, {ok_lbl}").unwrap();
            writeln!(asm, "    ld a, {}", PanicCode::AssertionFailed as u8).unwrap();
            writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
            writeln!(asm, "    call __aun_panic").unwrap();
            writeln!(asm, "{ok_lbl}:").unwrap();
        }
        IrInst::Panic { code, site_id } => {
            *needs_panic_stub = true;
            writeln!(asm, "    ld a, {}", *code as u8).unwrap();
            writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
            writeln!(asm, "    call __aun_panic").unwrap();
        }
        IrInst::StateTag {
            dst,
            machine_addr,
            machine_id,
        } => {
            let ma = val_addr(scratch_base, *machine_addr);
            let da = val_addr(scratch_base, *dst);
            let mdef = &program.machines[*machine_id as usize];
            writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
            if mdef.tag_offset > 0 {
                writeln!(asm, "    ld de, 0x{:04X}", mdef.tag_offset).unwrap();
                writeln!(asm, "    add hl, de").unwrap();
            }
            writeln!(asm, "    ld a, (hl)").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        IrInst::StateDispatch {
            dst,
            machine_addr,
            machine_id,
            method,
            args,
        } => {
            let mdef = &program.machines[*machine_id as usize];
            // Copy args 1..N into every implementing state's Uchiguri parameter slots
            for st in &mdef.states {
                if let Some(&fid) = st.methods.get(method) {
                    let callee = &program.functions[fid as usize];
                    for (idx, &arg_val) in args.iter().enumerate() {
                        if let Some(param_slot) = callee.locals.get(idx + 1) {
                            let aa = val_addr(scratch_base, arg_val);
                            let pa = layout.slot_addrs[&(callee.id, param_slot.id)];
                            match program.type_size(&param_slot.ty) {
                                1 => {
                                    writeln!(asm, "    ld a, (0x{aa:04X})").unwrap();
                                    writeln!(asm, "    ld (0x{pa:04X}), a").unwrap();
                                }
                                2 => {
                                    writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
                                    writeln!(asm, "    ld (0x{pa:04X}), hl").unwrap();
                                }
                                _ => {}
                            }
                        }
                    }
                }
            }
            let ma = val_addr(scratch_base, *machine_addr);
            writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
            writeln!(asm, "    call {}_disp_{method}", mdef.name).unwrap();
            if let Some(d) = dst {
                let da = val_addr(scratch_base, *d);
                writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
            }
        }
        IrInst::StateTransition {
            machine_addr,
            machine_id,
            from_state,
            to_state,
            field_vals,
            site_id,
        } => {
            let ma = val_addr(scratch_base, *machine_addr);
            let mdef = &program.machines[*machine_id as usize];

            // 1. Dynamic transition verification when `from_state` is unknown
            if from_state.is_none() {
                *needs_panic_stub = true;
                let ok_lbl = fresh_label(func, "tr_ok", label_counter);
                writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
                if mdef.tag_offset > 0 {
                    writeln!(asm, "    ld de, 0x{:04X}", mdef.tag_offset).unwrap();
                    writeln!(asm, "    add hl, de").unwrap();
                }
                writeln!(asm, "    ld a, (hl)").unwrap();
                writeln!(asm, "    add a, a").unwrap();
                writeln!(asm, "    ld e, a").unwrap();
                writeln!(asm, "    ld d, 0").unwrap();
                writeln!(asm, "    ld hl, {}_tmask", mdef.name).unwrap();
                writeln!(asm, "    add hl, de").unwrap();
                let bit = *to_state;
                if bit < 8 {
                    writeln!(asm, "    ld a, (hl)").unwrap();
                    writeln!(asm, "    bit {bit}, a").unwrap();
                } else {
                    writeln!(asm, "    inc hl").unwrap();
                    writeln!(asm, "    ld a, (hl)").unwrap();
                    writeln!(asm, "    bit {}, a", bit - 8).unwrap();
                }
                writeln!(asm, "    jr nz, {ok_lbl}").unwrap();
                writeln!(asm, "    ld a, {}", PanicCode::InvalidTransition as u8).unwrap();
                writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
                writeln!(asm, "    call __aun_panic").unwrap();
                writeln!(asm, "{ok_lbl}:").unwrap();
            }

            // 2. Call current state's on_exit
            if let Some(from) = from_state {
                if let Some(exit_fn) = mdef.states[*from as usize].on_exit {
                    let ename = z80_sym(&program.functions[exit_fn as usize].name);
                    writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
                    writeln!(asm, "    call {ename}").unwrap();
                }
            } else if mdef.states.iter().any(|s| s.on_exit.is_some()) {
                writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
                writeln!(asm, "    call {}_disp_on_exit", mdef.name).unwrap();
            }

            // 3. Write pre-evaluated payload fields into overlaid RAM region
            for (rel_off, vid, fty) in field_vals {
                let va = val_addr(scratch_base, *vid);
                let total_off = mdef.payload_offset + *rel_off;
                writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
                if total_off > 0 {
                    writeln!(asm, "    ld de, 0x{total_off:04X}").unwrap();
                    writeln!(asm, "    add hl, de").unwrap();
                }
                match program.type_size(fty) {
                    1 => {
                        writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                        writeln!(asm, "    ld (hl), a").unwrap();
                    }
                    2 => {
                        writeln!(asm, "    ld de, (0x{va:04X})").unwrap();
                        writeln!(asm, "    ld (hl), e").unwrap();
                        writeln!(asm, "    inc hl").unwrap();
                        writeln!(asm, "    ld (hl), d").unwrap();
                    }
                    _ => {}
                }
            }

            // 4. Write new state tag
            writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
            if mdef.tag_offset > 0 {
                writeln!(asm, "    ld de, 0x{:04X}", mdef.tag_offset).unwrap();
                writeln!(asm, "    add hl, de").unwrap();
            }
            writeln!(asm, "    ld (hl), {}", *to_state).unwrap();
            writeln!(asm, "    inc hl").unwrap();
            writeln!(asm, "    ld (hl), 0").unwrap();

            // 5. If #[smc], patch direct JP target in RAM for each dispatched method
            if mdef.smc {
                let mut methods: BTreeSet<String> = BTreeSet::new();
                for st in &mdef.states {
                    for m in st.methods.keys() {
                        methods.insert(m.clone());
                    }
                }
                for method in methods {
                    let target = mdef.states[*to_state as usize]
                        .methods
                        .get(&method)
                        .map(|&fid| z80_sym(&program.functions[fid as usize].name))
                        .unwrap_or_else(|| "__aun_noop_ret".to_string());
                    writeln!(asm, "    ld hl, {target}").unwrap();
                    writeln!(asm, "    ld ({}_disp_{method}+1), hl", mdef.name).unwrap();
                }
            }

            // 6. Call target state's on_enter
            if let Some(enter_fn) = mdef.states[*to_state as usize].on_enter {
                let ename = z80_sym(&program.functions[enter_fn as usize].name);
                writeln!(asm, "    ld hl, (0x{ma:04X})").unwrap();
                writeln!(asm, "    call {ename}").unwrap();
            }
        }
        IrInst::PoolAlloc {
            dst,
            pool_addr,
            init_addr,
            elem_size,
            capacity,
        } => {
            let pa = val_addr(scratch_base, *pool_addr);
            let ia = val_addr(scratch_base, *init_addr);
            let da = val_addr(scratch_base, *dst);
            let scan_lbl = fresh_label(func, "palloc_scan", label_counter);
            let bit_lbl = fresh_label(func, "palloc_bit", label_counter);
            let found_lbl = fresh_label(func, "palloc_found", label_counter);
            let done_lbl = fresh_label(func, "palloc_done", label_counter);
            let bm_off = elem_size * capacity;

            // Scan slots 0..capacity-1 for first free bit in alive bitmap
            writeln!(asm, "    ld c, 0").unwrap(); // C = candidate index
            writeln!(asm, "{scan_lbl}:").unwrap();
            writeln!(asm, "    ld a, c").unwrap();
            writeln!(asm, "    cp {}", *capacity as u8).unwrap();
            writeln!(asm, "    jr c, {bit_lbl}").unwrap();
            writeln!(asm, "    ld a, 0xFF").unwrap();
            writeln!(asm, "    jr {done_lbl}").unwrap();
            writeln!(asm, "{bit_lbl}:").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    ld e, a").unwrap();
            writeln!(asm, "    ld d, 0").unwrap();
            writeln!(asm, "    ld hl, (0x{pa:04X})").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ld de, 0x{bm_off:04X}").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            // Build bitmask for (C & 7) in B
            writeln!(asm, "    ld a, c").unwrap();
            writeln!(asm, "    and 7").unwrap();
            writeln!(asm, "    ld b, 1").unwrap();
            let shift_done = fresh_label(func, "palloc_sd", label_counter);
            let shift_loop = fresh_label(func, "palloc_sl", label_counter);
            writeln!(asm, "    or a").unwrap();
            writeln!(asm, "    jr z, {shift_done}").unwrap();
            writeln!(asm, "{shift_loop}:").unwrap();
            writeln!(asm, "    sla b").unwrap();
            writeln!(asm, "    dec a").unwrap();
            writeln!(asm, "    jr nz, {shift_loop}").unwrap();
            writeln!(asm, "{shift_done}:").unwrap();
            writeln!(asm, "    ld a, (hl)").unwrap();
            writeln!(asm, "    and b").unwrap();
            writeln!(asm, "    jr z, {found_lbl}").unwrap();
            writeln!(asm, "    inc c").unwrap();
            writeln!(asm, "    jr {scan_lbl}").unwrap();
            writeln!(asm, "{found_lbl}:").unwrap();
            // Mark alive bit
            writeln!(asm, "    ld a, (hl)").unwrap();
            writeln!(asm, "    or b").unwrap();
            writeln!(asm, "    ld (hl), a").unwrap();
            // Copy elem_size bytes from init_addr to pool_addr + C * elem_size using LDIR
            writeln!(asm, "    push bc").unwrap();
            writeln!(asm, "    ld l, c").unwrap();
            writeln!(asm, "    ld h, 0").unwrap();
            emit_mul_hl_const(*elem_size, asm);
            writeln!(asm, "    ld de, (0x{pa:04X})").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ex de, hl").unwrap(); // DE = dst
            writeln!(asm, "    ld hl, (0x{ia:04X})").unwrap(); // HL = src
            writeln!(asm, "    ld bc, 0x{elem_size:04X}").unwrap();
            writeln!(asm, "    ldir").unwrap();
            writeln!(asm, "    pop bc").unwrap();
            writeln!(asm, "    ld a, c").unwrap();
            writeln!(asm, "{done_lbl}:").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        IrInst::PoolFree {
            pool_addr,
            handle,
            elem_size,
            capacity,
            site_id,
        } => {
            *needs_panic_stub = true;
            let pa = val_addr(scratch_base, *pool_addr);
            let ha = val_addr(scratch_base, *handle);
            let bm_off = elem_size * capacity;
            let ok_rng = fresh_label(func, "pfree_rng", label_counter);
            let ok_live = fresh_label(func, "pfree_live", label_counter);
            let sd = fresh_label(func, "pfree_sd", label_counter);
            let sl = fresh_label(func, "pfree_sl", label_counter);
            writeln!(asm, "    ld a, (0x{ha:04X})").unwrap();
            writeln!(asm, "    cp {}", *capacity as u8).unwrap();
            writeln!(asm, "    jr c, {ok_rng}").unwrap();
            writeln!(asm, "    ld a, {}", PanicCode::InvalidHandle as u8).unwrap();
            writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
            writeln!(asm, "    call __aun_panic").unwrap();
            writeln!(asm, "{ok_rng}:").unwrap();
            writeln!(asm, "    ld c, a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    ld e, a").unwrap();
            writeln!(asm, "    ld d, 0").unwrap();
            writeln!(asm, "    ld hl, (0x{pa:04X})").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ld de, 0x{bm_off:04X}").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ld a, c").unwrap();
            writeln!(asm, "    and 7").unwrap();
            writeln!(asm, "    ld b, 1").unwrap();
            writeln!(asm, "    or a").unwrap();
            writeln!(asm, "    jr z, {sd}").unwrap();
            writeln!(asm, "{sl}:").unwrap();
            writeln!(asm, "    sla b").unwrap();
            writeln!(asm, "    dec a").unwrap();
            writeln!(asm, "    jr nz, {sl}").unwrap();
            writeln!(asm, "{sd}:").unwrap();
            writeln!(asm, "    ld a, (hl)").unwrap();
            writeln!(asm, "    and b").unwrap();
            writeln!(asm, "    jr nz, {ok_live}").unwrap();
            writeln!(asm, "    ld a, {}", PanicCode::InvalidHandle as u8).unwrap();
            writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
            writeln!(asm, "    call __aun_panic").unwrap();
            writeln!(asm, "{ok_live}:").unwrap();
            writeln!(asm, "    ld a, b").unwrap();
            writeln!(asm, "    cpl").unwrap();
            writeln!(asm, "    and (hl)").unwrap();
            writeln!(asm, "    ld (hl), a").unwrap();
        }
        IrInst::PoolElemAddr {
            dst,
            pool_addr,
            handle,
            elem_size,
            capacity,
            site_id,
        } => {
            *needs_panic_stub = true;
            let pa = val_addr(scratch_base, *pool_addr);
            let ha = val_addr(scratch_base, *handle);
            let da = val_addr(scratch_base, *dst);
            let bm_off = elem_size * capacity;
            let ok_rng = fresh_label(func, "pget_rng", label_counter);
            let ok_live = fresh_label(func, "pget_live", label_counter);
            let sd = fresh_label(func, "pget_sd", label_counter);
            let sl = fresh_label(func, "pget_sl", label_counter);
            writeln!(asm, "    ld a, (0x{ha:04X})").unwrap();
            writeln!(asm, "    cp {}", *capacity as u8).unwrap();
            writeln!(asm, "    jr c, {ok_rng}").unwrap();
            writeln!(asm, "    ld a, {}", PanicCode::InvalidHandle as u8).unwrap();
            writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
            writeln!(asm, "    call __aun_panic").unwrap();
            writeln!(asm, "{ok_rng}:").unwrap();
            writeln!(asm, "    ld c, a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    srl a").unwrap();
            writeln!(asm, "    ld e, a").unwrap();
            writeln!(asm, "    ld d, 0").unwrap();
            writeln!(asm, "    ld hl, (0x{pa:04X})").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ld de, 0x{bm_off:04X}").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ld a, c").unwrap();
            writeln!(asm, "    and 7").unwrap();
            writeln!(asm, "    ld b, 1").unwrap();
            writeln!(asm, "    or a").unwrap();
            writeln!(asm, "    jr z, {sd}").unwrap();
            writeln!(asm, "{sl}:").unwrap();
            writeln!(asm, "    sla b").unwrap();
            writeln!(asm, "    dec a").unwrap();
            writeln!(asm, "    jr nz, {sl}").unwrap();
            writeln!(asm, "{sd}:").unwrap();
            writeln!(asm, "    ld a, (hl)").unwrap();
            writeln!(asm, "    and b").unwrap();
            writeln!(asm, "    jr nz, {ok_live}").unwrap();
            writeln!(asm, "    ld a, {}", PanicCode::InvalidHandle as u8).unwrap();
            writeln!(asm, "    ld hl, 0x{site_id:04X}").unwrap();
            writeln!(asm, "    call __aun_panic").unwrap();
            writeln!(asm, "{ok_live}:").unwrap();
            writeln!(asm, "    ld l, c").unwrap();
            writeln!(asm, "    ld h, 0").unwrap();
            emit_mul_hl_const(*elem_size, asm);
            writeln!(asm, "    ld de, (0x{pa:04X})").unwrap();
            writeln!(asm, "    add hl, de").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::InlineAsm { template, .. } => {
            for line in template.split(';') {
                let t = line.trim();
                if !t.is_empty() {
                    writeln!(asm, "    {t}").unwrap();
                }
            }
        }
    }
    Ok(())
}

/// Multiplies `HL` by a compile-time constant `k` in-place (clobbers `DE`).
fn emit_mul_hl_const(k: u16, asm: &mut String) {
    match k {
        0 => writeln!(asm, "    ld hl, 0").unwrap(),
        1 => {}
        n if n.is_power_of_two() => {
            for _ in 0..n.trailing_zeros() {
                writeln!(asm, "    add hl, hl").unwrap();
            }
        }
        n => {
            // Binary shift-and-add: DE = original HL, start from MSB
            writeln!(asm, "    ld d, h").unwrap();
            writeln!(asm, "    ld e, l").unwrap();
            let msb = 15 - n.leading_zeros();
            for bit in (0..msb).rev() {
                writeln!(asm, "    add hl, hl").unwrap();
                if ((n >> bit) & 1) != 0 {
                    writeln!(asm, "    add hl, de").unwrap();
                }
            }
        }
    }
}

#[allow(clippy::too_many_arguments)]
fn emit_binop(
    program: &IrProgram,
    func: &IrFunction,
    dst: ValueId,
    op: IrBinOp,
    mode: ArithMode,
    ty: &IrType,
    lhs: ValueId,
    rhs: ValueId,
    scratch_base: u16,
    label_counter: &mut u32,
    asm: &mut String,
) {
    let la = val_addr(scratch_base, lhs);
    let ra = val_addr(scratch_base, rhs);
    let da = val_addr(scratch_base, dst);
    let signed = is_signed_ty(ty);

    // Handle comparisons first (result is always 1-byte Bool in A)
    let is_cmp = matches!(
        op,
        IrBinOp::Eq | IrBinOp::Ne | IrBinOp::Lt | IrBinOp::Le | IrBinOp::Gt | IrBinOp::Ge
    );
    if is_cmp {
        let done = fresh_label(func, "cmp", label_counter);
        let (a_addr, b_addr, cc) = match op {
            IrBinOp::Eq => (la, ra, "z"),
            IrBinOp::Ne => (la, ra, "nz"),
            IrBinOp::Lt => (la, ra, "c"),
            IrBinOp::Ge => (la, ra, "nc"),
            // a <= b  <=>  b >= a
            IrBinOp::Le => (ra, la, "nc"),
            // a > b   <=>  b < a
            IrBinOp::Gt => (ra, la, "c"),
            _ => unreachable!(),
        };
        let ordered = !matches!(op, IrBinOp::Eq | IrBinOp::Ne);
        match program.type_size(ty) {
            1 => {
                writeln!(asm, "    ld a, (0x{b_addr:04X})").unwrap();
                if signed && ordered {
                    writeln!(asm, "    xor 0x80").unwrap();
                }
                writeln!(asm, "    ld b, a").unwrap();
                writeln!(asm, "    ld a, (0x{a_addr:04X})").unwrap();
                if signed && ordered {
                    writeln!(asm, "    xor 0x80").unwrap();
                }
                writeln!(asm, "    cp b").unwrap();
                writeln!(asm, "    ld a, 1").unwrap();
                writeln!(asm, "    jr {cc}, {done}").unwrap();
                writeln!(asm, "    xor a").unwrap();
                writeln!(asm, "{done}:").unwrap();
                writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
            }
            2 => {
                writeln!(asm, "    ld hl, (0x{a_addr:04X})").unwrap();
                if signed && ordered {
                    writeln!(asm, "    ld a, h").unwrap();
                    writeln!(asm, "    xor 0x80").unwrap();
                    writeln!(asm, "    ld h, a").unwrap();
                }
                writeln!(asm, "    ld de, (0x{b_addr:04X})").unwrap();
                if signed && ordered {
                    writeln!(asm, "    ld a, d").unwrap();
                    writeln!(asm, "    xor 0x80").unwrap();
                    writeln!(asm, "    ld d, a").unwrap();
                }
                writeln!(asm, "    or a").unwrap();
                writeln!(asm, "    sbc hl, de").unwrap();
                writeln!(asm, "    ld a, 1").unwrap();
                writeln!(asm, "    jr {cc}, {done}").unwrap();
                writeln!(asm, "    xor a").unwrap();
                writeln!(asm, "{done}:").unwrap();
                writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
            }
            _ => {}
        }
        return;
    }

    match program.type_size(ty) {
        1 => {
            if matches!(op, IrBinOp::Shl | IrBinOp::Shr) {
                let loop_lbl = fresh_label(func, "sh_lp", label_counter);
                let done_lbl = fresh_label(func, "sh_dn", label_counter);
                writeln!(asm, "    ld a, (0x{ra:04X})").unwrap();
                writeln!(asm, "    ld b, a").unwrap();
                writeln!(asm, "    ld a, (0x{la:04X})").unwrap();
                writeln!(asm, "    inc b").unwrap();
                writeln!(asm, "    dec b").unwrap();
                writeln!(asm, "    jr z, {done_lbl}").unwrap();
                writeln!(asm, "{loop_lbl}:").unwrap();
                match op {
                    IrBinOp::Shl => writeln!(asm, "    sla a").unwrap(),
                    IrBinOp::Shr if signed => writeln!(asm, "    sra a").unwrap(),
                    IrBinOp::Shr => writeln!(asm, "    srl a").unwrap(),
                    _ => unreachable!(),
                }
                writeln!(asm, "    djnz {loop_lbl}").unwrap();
                writeln!(asm, "{done_lbl}:").unwrap();
                writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                return;
            }
            writeln!(asm, "    ld a, (0x{ra:04X})").unwrap();
            writeln!(asm, "    ld b, a").unwrap();
            writeln!(asm, "    ld a, (0x{la:04X})").unwrap();
            match (op, mode) {
                (IrBinOp::Add, ArithMode::Saturating) if !signed => {
                    let lbl = fresh_label(func, "sat", label_counter);
                    writeln!(asm, "    add a, b").unwrap();
                    writeln!(asm, "    jr nc, {lbl}").unwrap();
                    writeln!(asm, "    ld a, 0xFF").unwrap();
                    writeln!(asm, "{lbl}:").unwrap();
                }
                (IrBinOp::Sub, ArithMode::Saturating) if !signed => {
                    let lbl = fresh_label(func, "sat", label_counter);
                    writeln!(asm, "    sub b").unwrap();
                    writeln!(asm, "    jr nc, {lbl}").unwrap();
                    writeln!(asm, "    xor a").unwrap();
                    writeln!(asm, "{lbl}:").unwrap();
                }
                (IrBinOp::Add, ArithMode::Saturating) => {
                    let lbl = fresh_label(func, "sat", label_counter);
                    writeln!(asm, "    add a, b").unwrap();
                    writeln!(asm, "    jp po, {lbl}").unwrap();
                    writeln!(asm, "    ld a, 0x7F").unwrap();
                    writeln!(asm, "    jp m, {lbl}").unwrap();
                    writeln!(asm, "    ld a, 0x80").unwrap();
                    writeln!(asm, "{lbl}:").unwrap();
                }
                (IrBinOp::Sub, ArithMode::Saturating) => {
                    let lbl = fresh_label(func, "sat", label_counter);
                    writeln!(asm, "    sub b").unwrap();
                    writeln!(asm, "    jp po, {lbl}").unwrap();
                    writeln!(asm, "    ld a, 0x7F").unwrap();
                    writeln!(asm, "    jp m, {lbl}").unwrap();
                    writeln!(asm, "    ld a, 0x80").unwrap();
                    writeln!(asm, "{lbl}:").unwrap();
                }
                (IrBinOp::Add, _) => writeln!(asm, "    add a, b").unwrap(),
                (IrBinOp::Sub, _) => writeln!(asm, "    sub b").unwrap(),
                (IrBinOp::BitAnd, _) => writeln!(asm, "    and b").unwrap(),
                (IrBinOp::BitOr, _) => writeln!(asm, "    or b").unwrap(),
                (IrBinOp::BitXor, _) => writeln!(asm, "    xor b").unwrap(),
                _ => {}
            }
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        2 => {
            if matches!(op, IrBinOp::Shl | IrBinOp::Shr) {
                let loop_lbl = fresh_label(func, "sh16_lp", label_counter);
                let done_lbl = fresh_label(func, "sh16_dn", label_counter);
                writeln!(asm, "    ld a, (0x{ra:04X})").unwrap();
                writeln!(asm, "    ld b, a").unwrap();
                writeln!(asm, "    ld hl, (0x{la:04X})").unwrap();
                writeln!(asm, "    inc b").unwrap();
                writeln!(asm, "    dec b").unwrap();
                writeln!(asm, "    jr z, {done_lbl}").unwrap();
                writeln!(asm, "{loop_lbl}:").unwrap();
                match op {
                    IrBinOp::Shl => writeln!(asm, "    add hl, hl").unwrap(),
                    IrBinOp::Shr if signed => {
                        writeln!(asm, "    sra h").unwrap();
                        writeln!(asm, "    rr l").unwrap();
                    }
                    IrBinOp::Shr => {
                        writeln!(asm, "    srl h").unwrap();
                        writeln!(asm, "    rr l").unwrap();
                    }
                    _ => unreachable!(),
                }
                writeln!(asm, "    djnz {loop_lbl}").unwrap();
                writeln!(asm, "{done_lbl}:").unwrap();
                writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                return;
            }
            writeln!(asm, "    ld hl, (0x{la:04X})").unwrap();
            writeln!(asm, "    ld de, (0x{ra:04X})").unwrap();
            match op {
                IrBinOp::Add => writeln!(asm, "    add hl, de").unwrap(),
                IrBinOp::Sub => {
                    writeln!(asm, "    or a").unwrap();
                    writeln!(asm, "    sbc hl, de").unwrap();
                }
                IrBinOp::BitAnd => {
                    writeln!(asm, "    ld a, l").unwrap();
                    writeln!(asm, "    and e").unwrap();
                    writeln!(asm, "    ld l, a").unwrap();
                    writeln!(asm, "    ld a, h").unwrap();
                    writeln!(asm, "    and d").unwrap();
                    writeln!(asm, "    ld h, a").unwrap();
                }
                IrBinOp::BitOr => {
                    writeln!(asm, "    ld a, l").unwrap();
                    writeln!(asm, "    or e").unwrap();
                    writeln!(asm, "    ld l, a").unwrap();
                    writeln!(asm, "    ld a, h").unwrap();
                    writeln!(asm, "    or d").unwrap();
                    writeln!(asm, "    ld h, a").unwrap();
                }
                IrBinOp::BitXor => {
                    writeln!(asm, "    ld a, l").unwrap();
                    writeln!(asm, "    xor e").unwrap();
                    writeln!(asm, "    ld l, a").unwrap();
                    writeln!(asm, "    ld a, h").unwrap();
                    writeln!(asm, "    xor d").unwrap();
                    writeln!(asm, "    ld h, a").unwrap();
                }
                _ => {}
            }
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        _ => {}
    }
}
