//! Phase 1 Z80 code generator lowering `aun-ir` + *Uchiguri* static RAM layout to Z80 assembly.

use crate::uchiguri::RamLayout;
use aun_ir::*;
use std::fmt::Write;

/// Emits Z80 assembly text for all non-test functions in `program`.
pub fn emit_z80_asm(program: &IrProgram, layout: &RamLayout, code_origin: u16) -> Result<String, String> {
    let mut asm = String::new();
    writeln!(asm, "; Generated by aun-z80 (Phase 1)").unwrap();
    writeln!(asm, ".org 0x{code_origin:04X}").unwrap();
    writeln!(asm, "; Uchiguri RAM: 0x{:04X}..0x{:04X} ({} bytes), max stack: {} bytes",
        layout.ram_base,
        layout.ram_end,
        layout.ram_end.saturating_sub(layout.ram_base),
        layout.max_stack_bytes
    ).unwrap();

    // Reserve scratch area for temporary SSA values right after Uchiguri RAM
    let scratch_base = layout.ram_end;

    for func in &program.functions {
        if func.is_test {
            continue;
        }
        emit_function(program, func, layout, scratch_base, &mut asm)?;
    }

    Ok(asm)
}

fn val_addr(scratch_base: u16, v: ValueId) -> u16 {
    scratch_base.wrapping_add((v as u16) * 2)
}

fn emit_function(
    program: &IrProgram,
    func: &IrFunction,
    layout: &RamLayout,
    scratch_base: u16,
    asm: &mut String,
) -> Result<(), String> {
    writeln!(asm, "\n{}:", func.name).unwrap();

    // Entry: if 1st param is 8-bit -> A, 16-bit -> HL, store to its static Uchiguri slot
    if func.param_count > 0 {
        let p0 = &func.locals[0];
        let p0_addr = layout.slot_addrs[&(func.id, p0.id)];
        match p0.ty.byte_size(&program.structs) {
            1 => writeln!(asm, "    ld (0x{p0_addr:04X}), a").unwrap(),
            2 => writeln!(asm, "    ld (0x{p0_addr:04X}), hl").unwrap(),
            _ => {}
        }
    }

    for bb in &func.blocks {
        writeln!(asm, "{}_bb{}:", func.name, bb.id).unwrap();
        for inst in &bb.insts {
            emit_inst(program, func, inst, layout, scratch_base, asm)?;
        }
        match bb.term {
            Terminator::Return(Some(v)) => {
                let va = val_addr(scratch_base, v);
                match func.ret_ty.byte_size(&program.structs) {
                    1 => writeln!(asm, "    ld a, (0x{va:04X})").unwrap(),
                    2 => writeln!(asm, "    ld hl, (0x{va:04X})").unwrap(),
                    _ => {}
                }
                writeln!(asm, "    ret").unwrap();
            }
            Terminator::Return(None) => {
                writeln!(asm, "    ret").unwrap();
            }
            Terminator::Goto(target) => {
                writeln!(asm, "    jp {}_bb{target}", func.name).unwrap();
            }
            Terminator::Branch {
                cond,
                then_bb,
                else_bb,
            } => {
                let ca = val_addr(scratch_base, cond);
                writeln!(asm, "    ld a, (0x{ca:04X})").unwrap();
                writeln!(asm, "    or a").unwrap();
                writeln!(asm, "    jp nz, {}_bb{then_bb}", func.name).unwrap();
                writeln!(asm, "    jp {}_bb{else_bb}", func.name).unwrap();
            }
            Terminator::Unreachable => {
                writeln!(asm, "    halt").unwrap();
            }
        }
    }
    Ok(())
}

fn emit_inst(
    program: &IrProgram,
    func: &IrFunction,
    inst: &IrInst,
    layout: &RamLayout,
    scratch_base: u16,
    asm: &mut String,
) -> Result<(), String> {
    match inst {
        IrInst::ConstInt { dst, ty, val } => {
            let da = val_addr(scratch_base, *dst);
            match ty.byte_size(&program.structs) {
                1 => {
                    let b = (*val & 0xFF) as u8;
                    if b == 0 {
                        writeln!(asm, "    xor a").unwrap();
                    } else {
                        writeln!(asm, "    ld a, 0x{b:02X}").unwrap();
                    }
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                2 => {
                    let w = *val as u16;
                    writeln!(asm, "    ld hl, 0x{w:04X}").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::ConstBool { dst, val } => {
            let da = val_addr(scratch_base, *dst);
            if *val {
                writeln!(asm, "    ld a, 1").unwrap();
            } else {
                writeln!(asm, "    xor a").unwrap();
            }
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        IrInst::LoadLocal { dst, slot, ty } => {
            let sa = layout.slot_addrs[&(func.id, *slot)];
            let da = val_addr(scratch_base, *dst);
            match ty.byte_size(&program.structs) {
                1 => {
                    writeln!(asm, "    ld a, (0x{sa:04X})").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld hl, (0x{sa:04X})").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::StoreLocal { slot, val, ty } => {
            let sa = layout.slot_addrs[&(func.id, *slot)];
            let va = val_addr(scratch_base, *val);
            match ty.byte_size(&program.structs) {
                1 => {
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (0x{sa:04X}), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld hl, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (0x{sa:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::AddrLocal { dst, slot } => {
            let sa = layout.slot_addrs[&(func.id, *slot)];
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, 0x{sa:04X}").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::AddrGlobal { dst, global } => {
            let ga = layout.global_addrs[global];
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, 0x{ga:04X}").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::FieldAddr {
            dst,
            base,
            byte_offset,
        } => {
            let ba = val_addr(scratch_base, *base);
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, (0x{ba:04X})").unwrap();
            if *byte_offset > 0 {
                writeln!(asm, "    ld de, 0x{byte_offset:04X}").unwrap();
                writeln!(asm, "    add hl, de").unwrap();
            }
            writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
        }
        IrInst::LoadPtr { dst, addr, ty } => {
            let aa = val_addr(scratch_base, *addr);
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
            match ty.byte_size(&program.structs) {
                1 => {
                    writeln!(asm, "    ld a, (hl)").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld e, (hl)").unwrap();
                    writeln!(asm, "    inc hl").unwrap();
                    writeln!(asm, "    ld d, (hl)").unwrap();
                    writeln!(asm, "    ex de, hl").unwrap();
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::StorePtr { addr, val, ty } => {
            let aa = val_addr(scratch_base, *addr);
            let va = val_addr(scratch_base, *val);
            match ty.byte_size(&program.structs) {
                1 => {
                    writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
                    writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld (hl), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld de, (0x{va:04X})").unwrap();
                    writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap();
                    writeln!(asm, "    ld (hl), e").unwrap();
                    writeln!(asm, "    inc hl").unwrap();
                    writeln!(asm, "    ld (hl), d").unwrap();
                }
                _ => {}
            }
        }
        IrInst::FixedInt {
            dst,
            val,
            frac_bits: 8,
            ..
        } => {
            // q8_8::int() -> direct high-byte read (0T shift!)
            let va_hi = val_addr(scratch_base, *val).wrapping_add(1);
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld a, (0x{va_hi:04X})").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        IrInst::BinOp {
            dst,
            op,
            mode,
            ty,
            lhs,
            rhs,
            ..
        } => {
            let la = val_addr(scratch_base, *lhs);
            let ra = val_addr(scratch_base, *rhs);
            let da = val_addr(scratch_base, *dst);
            match ty.byte_size(&program.structs) {
                1 => {
                    writeln!(asm, "    ld a, (0x{ra:04X})").unwrap();
                    writeln!(asm, "    ld b, a").unwrap();
                    writeln!(asm, "    ld a, (0x{la:04X})").unwrap();
                    match (op, mode) {
                        (IrBinOp::Add, ArithMode::Saturating) => {
                            let lbl = format!("{}_sat_{dst}", func.name);
                            writeln!(asm, "    add a, b").unwrap();
                            writeln!(asm, "    jr nc, {lbl}").unwrap();
                            writeln!(asm, "    ld a, 0xFF").unwrap();
                            writeln!(asm, "{lbl}:").unwrap();
                        }
                        (IrBinOp::Sub, ArithMode::Saturating) => {
                            let lbl = format!("{}_sat_{dst}", func.name);
                            writeln!(asm, "    sub b").unwrap();
                            writeln!(asm, "    jr nc, {lbl}").unwrap();
                            writeln!(asm, "    xor a").unwrap();
                            writeln!(asm, "{lbl}:").unwrap();
                        }
                        (IrBinOp::Add, _) => writeln!(asm, "    add a, b").unwrap(),
                        (IrBinOp::Sub, _) => writeln!(asm, "    sub b").unwrap(),
                        (IrBinOp::BitAnd, _) => writeln!(asm, "    and b").unwrap(),
                        (IrBinOp::BitOr, _) => writeln!(asm, "    or b").unwrap(),
                        (IrBinOp::BitXor, _) => writeln!(asm, "    xor b").unwrap(),
                        _ => {}
                    }
                    writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                }
                2 => {
                    writeln!(asm, "    ld hl, (0x{la:04X})").unwrap();
                    writeln!(asm, "    ld de, (0x{ra:04X})").unwrap();
                    match op {
                        IrBinOp::Add => writeln!(asm, "    add hl, de").unwrap(),
                        IrBinOp::Sub => {
                            writeln!(asm, "    or a").unwrap();
                            writeln!(asm, "    sbc hl, de").unwrap();
                        }
                        _ => {}
                    }
                    writeln!(asm, "    ld (0x{da:04X}), hl").unwrap();
                }
                _ => {}
            }
        }
        IrInst::PortOut { port, val } => {
            let pa = val_addr(scratch_base, *port);
            let va = val_addr(scratch_base, *val);
            writeln!(asm, "    ld a, (0x{pa:04X})").unwrap();
            writeln!(asm, "    ld c, a").unwrap();
            writeln!(asm, "    ld a, (0x{va:04X})").unwrap();
            writeln!(asm, "    out (c), a").unwrap();
        }
        IrInst::PortIn { dst, port } => {
            let pa = val_addr(scratch_base, *port);
            let da = val_addr(scratch_base, *dst);
            writeln!(asm, "    ld a, (0x{pa:04X})").unwrap();
            writeln!(asm, "    ld c, a").unwrap();
            writeln!(asm, "    in a, (c)").unwrap();
            writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
        }
        IrInst::Call {
            dst,
            func: callee_id,
            args,
        } => {
            let callee = &program.functions[*callee_id as usize];
            if let Some(&a0) = args.first() {
                let aa = val_addr(scratch_base, a0);
                match callee.locals[0].ty.byte_size(&program.structs) {
                    1 => writeln!(asm, "    ld a, (0x{aa:04X})").unwrap(),
                    2 => writeln!(asm, "    ld hl, (0x{aa:04X})").unwrap(),
                    _ => {}
                }
            }
            writeln!(asm, "    call {}", callee.name).unwrap();
            if let Some(d) = dst {
                let da = val_addr(scratch_base, *d);
                match callee.ret_ty.byte_size(&program.structs) {
                    1 => writeln!(asm, "    ld (0x{da:04X}), a").unwrap(),
                    2 => writeln!(asm, "    ld (0x{da:04X}), hl").unwrap(),
                    _ => {}
                }
            }
        }
        IrInst::ExternCall {
            dst,
            extern_fn,
            args,
        } => {
            let ef = &program.externs[*extern_fn as usize];
            for (arg_val, (_, pty, reg)) in args.iter().zip(ef.params.iter()) {
                let aa = val_addr(scratch_base, *arg_val);
                let r = reg.to_ascii_lowercase();
                match pty.byte_size(&program.structs) {
                    1 => {
                        writeln!(asm, "    ld a, (0x{aa:04X})").unwrap();
                        if r != "a" {
                            writeln!(asm, "    ld {r}, a").unwrap();
                        }
                    }
                    2 => {
                        writeln!(asm, "    ld {r}, (0x{aa:04X})").unwrap();
                    }
                    _ => {}
                }
            }
            writeln!(asm, "    call {}", ef.name).unwrap();
            if let (Some(d), Some((rty, rreg))) = (dst, &ef.ret) {
                let da = val_addr(scratch_base, *d);
                let r = rreg.to_ascii_lowercase();
                match rty.byte_size(&program.structs) {
                    1 => {
                        if r != "a" {
                            writeln!(asm, "    ld a, {r}").unwrap();
                        }
                        writeln!(asm, "    ld (0x{da:04X}), a").unwrap();
                    }
                    2 => writeln!(asm, "    ld (0x{da:04X}), {r}").unwrap(),
                    _ => {}
                }
            }
        }
        IrInst::InlineAsm { template, .. } => {
            for line in template.split(';') {
                let t = line.trim();
                if !t.is_empty() {
                    writeln!(asm, "    {t}").unwrap();
                }
            }
        }
        _ => {}
    }
    Ok(())
}
